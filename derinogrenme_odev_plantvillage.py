class PlantDocDataset(Dataset):
    def __init__(self, root_dir, class_to_idx, transform=None):
        self.root_dir = Path(root_dir)
        self.class_to_idx = class_to_idx
        self.transform = transform
        self.samples = []

        # Her sınıf klasörünü gezerek resim ve etiket çiftlerini topla
        for class_name in sorted(os.listdir(self.root_dir)): # Iterate through class directories
            class_path = self.root_dir / class_name
            if not class_path.is_dir():
                continue

            class_idx = self.class_to_idx[class_name] # Get numerical index for class name

            for img_file in sorted(os.listdir(class_path)):
                if img_file.lower().endswith(('.png', '.jpg', '.jpeg')):
                    img_path = class_path / img_file
                    self.samples.append((img_path, class_idx))

        if not self.samples:
            raise FileNotFoundError(f"Belirtilen dizinde ({root_dir}) eşleşen resim ve etiket çifti bulunamadı. "
                                    "Sınıf klasörlerinin ve resimlerin doğru yerde olduğundan emin olun.")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        img_path, label = self.samples[idx]
        image = Image.open(img_path).convert('RGB')

        if self.transform:
            image = self.transform(image)

        return image, label

# A wrapper to apply transformations to a Subset
class TransformedSubset(Dataset):
    def __init__(self, subset, transform=None):
        self.subset = subset
        self.transform = transform

    def __getitem__(self, idx):
        image, label = self.subset[idx]
        if self.transform:
            image = self.transform(image)
        return image, label

    def __len__(self):
        return len(self.subset)

