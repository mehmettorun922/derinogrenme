def predict(img_path: str, top_k: int = 5):
    """
    Tek bir görseli sınıflandır ve top-k sonucu yazdır.

    Kullanım:
        predict('yaprak.jpg')           # top-5
        predict('yaprak.jpg', top_k=3) # top-3
    """
    # Tahmin fonksiyonunu daha sağlam hale getirmek için,
    # sınıf adlarını doğrudan checkpoint'ten yükleyelim.
    ckpt = torch.load(CFG['save_path'], map_location=device)
    model.load_state_dict(ckpt['model_state']) # Modelin doğru ağırlıklarla yüklendiğinden emin ol

    # ckpt['classes'] artık açıklayıcı isimleri içerdiğinden doğrudan kullanılabilir.
    current_classes = ckpt['classes'] # Sınıf adlarını checkpoint'ten al (şimdi açıklayıcı olmalı)

    tf = transforms.Compose([
        transforms.Resize((SZ, SZ)),
        transforms.ToTensor(),
        transforms.Normalize(MEAN, STD),
    ])
    img  = Image.open(img_path).convert('RGB')
    inp  = tf(img).unsqueeze(0).to(device)

    model.eval()
    with torch.no_grad():
        probs = torch.softmax(model(inp), dim=1)

    top_p, top_i = probs.topk(min(top_k, len(current_classes))) # 'num_classes' yerine 'len(current_classes)' kullan
    print(f'\n🌿  Tahmin: {img_path}')
    print('─' * 52)
    for p, i in zip(top_p[0], top_i[0]):
        bar = '█' * int(p.item() * 30)
        # 'current_classes' listesi artık açıklayıcı isimleri tuttuğu için doğrudan kullanılabilir.
        print(f'  {current_classes[i.item()]:38s} {bar} {p.item()*100:5.1f}%')

    best_class = current_classes[top_i[0][0].item()]
    best_prob  = top_p[0][0].item()
    print(f'\n  → Sonuç: {best_class}  (%{best_prob*100:.1f})')
    return best_class, best_prob


